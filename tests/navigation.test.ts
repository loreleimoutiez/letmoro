test('a new encounter moves only that person’s latest marker and retains a historical trace', () => {
  let run = apply(delivered(), { type: 'continue-neighborhood' });
  assert.equal(encounterMarkers(run).filter(item => item.character === 'recipient').length, 1);
  run = apply(apply(run, { type: 'choose-place', place: 'square' }), { type: 'steps', amount: 350 });
  assert.equal(currentNode(run), 'square');
  assert.equal(encounterMarkers(run).find(item => item.character === 'recipient')!.place, 'courtyard');
  run = apply(run, { type: 'meet-place', place: 'square' });
  const markers = encounterMarkers(run).filter(item => item.character === 'recipient');
  assert.deepEqual(markers.map(item => [item.place, item.latest]), [['courtyard', false], ['square', true]]);
  assert.equal(recordsFor(run).characters.find(item => item.id === 'recipient')!.lastKnownPlace, 'square');
  assert.equal(encounterMarkers(run).find(item => item.character === 'clerk')!.place, 'office');
  assert.deepEqual(decodeSave(encodeSave(run)), run);
});
test('voluntary multi-day help requires an equally funded return and pays no employment wages', () => {
  let run = apply(apply(delivered(), { type: 'continue-neighborhood' }), { type: 'choose-place', place: 'workshop' });
  run = apply(apply(run, { type: 'steps', amount: 500 }), { type: 'meet-place', place: 'workshop' });
  run = apply(run, { type: 'reply', reply: 'listen' });
  assert.throws(() => apply(run, { type: 'reply', reply: 'listen' }));
  run = apply(run, { type: 'reply', reply: 'help' });
  assert.equal(run.stage, 'errand');
  assert.equal(availableDirections(run).north!.edge, 'gate');
  assert.throws(() => apply(run, { type: 'inspect' }));
  run = apply(run, { type: 'steps', amount: 2000 });
  assert.equal(currentNode(run), 'gate');
  assert.equal(run.navigation!.heading, null);
  run = apply(run, { type: 'inspect' });
  assert.throws(() => apply(run, { type: 'finish-errand' }));
  run = apply(apply(run, { type: 'choose-direction', direction: 'south' }), { type: 'steps', amount: 1999 });
  assert.throws(() => apply(run, { type: 'finish-errand' }));
  run = apply(apply(run, { type: 'steps', amount: 1 }), { type: 'finish-errand' });
  assert.equal(run.stage, 'workshop');
  assert.deepEqual(run.completedErrands, ['workshop']);
  assert.equal(run.sous, 4);
  assert.equal(run.delivered, 1);
  assert.throws(() => apply(run, { type: 'reply', reply: 'help' }));
  assert.deepEqual(decodeSave(encodeSave(run)), run);
  run = apply(run, { type: 'finish-conversation' });
  run = apply(apply(run, { type: 'choose-direction', direction: 'west' }), { type: 'steps', amount: 500 });
  run = apply(apply(run, { type: 'choose-place', place: 'square' }), { type: 'steps', amount: 350 });
  run = apply(apply(run, { type: 'meet-place', place: 'square' }), { type: 'reply', reply: 'help' });
  assert(knownPlaces(run).includes('gate'));
  assert(!knownPlaces(run).includes('garden'), 'An earlier inspection must not reveal the next quest destination');
});
test('refusal can explore without employment and return to the sole job offer', () => {
  let run = apply(apply(apply(start(), { type: 'steps', amount: 20 }), { type: 'cross' }), { type: 'rest' });
  run = apply(apply(run, { type: 'explore-neighborhood' }), { type: 'choose-place', place: 'square' });
  run = apply(run, { type: 'steps', amount: 100 });
  assert.equal(currentNode(run), 'courtyard');
  assert.equal(run.reserve, 0);
  run = apply(apply(run, { type: 'choose-direction', direction: 'west' }), { type: 'steps', amount: 350 });
  run = apply(run, { type: 'meet-place', place: 'square' });
  assert.equal(recordsFor(run).letters.length, 0);
  assert.equal(recordsFor(run).skills.length, 0);
  assert.equal(recordsFor(run).characters.some(item => item.id === 'recipient'), false);
  run = apply(run, { type: 'finish-conversation' });
  run = apply(apply(run, { type: 'choose-direction', direction: 'east' }), { type: 'steps', amount: 350 });
  run = apply(apply(run, { type: 'choose-direction', direction: 'south' }), { type: 'steps', amount: 100 });
  run = apply(run, { type: 'return-to-offer' });
  assert.equal(apply(run, { type: 'accept' }).stage, 'delivery');
});
test('earned letter badges and basic respect are derived once and future entries stay hidden', () => {
  let run = createRun(1000);
  assert.equal(recordsFor(run).badges.filter(item => item.description !== null).length, 0);
  assert.equal(recordsFor(run).skills.length, 0);
  run = apply(apply(apply(run, { type: 'steps', amount: 120 }), { type: 'cross' }), { type: 'accept' });
  assert.deepEqual(recordsFor(run).skills, [{ id: 'basic-respect' }]);
  run = apply(run, { type: 'open-letter' });
  run = apply(run, { type: 'destroy-letter' });
  assert.deepEqual(recordsFor(run).badges.filter(item => item.description !== null).map(item => item.id), ['first-job', 'first-opening', 'first-destruction']);
  assert.equal(recordsFor(decodeSave(encodeSave(run))).badges.length, 3);
  assert.deepEqual(recordsFor(delivered()).badges.map(item => item.id), ['first-job', 'first-delivery']);
});
test('zoom supports early travel, bounded pinch ratios and wheel movement in both directions', () => {
  assert.equal(clampZoom(0), MIN_ZOOM);
  assert.equal(clampZoom(100), MAX_ZOOM);
  assert(wheelZoom(1, 120) < 1);
  assert(wheelZoom(1, -120) > 1);
  assert.equal(wheelZoom(MIN_ZOOM, 100000), MIN_ZOOM);
  assert.equal(wheelZoom(MAX_ZOOM, -100000), MAX_ZOOM);
});
